-- v3：删掉 schema_migrations 这张化石表
--
-- 这张表是**旧迁移链（v1–v31）的版本记录**，那条链已经被
-- migrations/01-baseline/up.sql + rusqlite_migration 取代（commit 6dbc582）。
-- 现在的版本真源只有一个：`PRAGMA user_version`，也就是 SQLite 文件头第 60
-- 字节起的那 4 个字节。rusqlite_migration 全 crate 从不读 schema_migrations
-- （0 处引用），本仓代码也不读（0 处引用）。
--
-- 留着它是有害的，不只是浪费：它声称「1–31」，而系统实际只有两条迁移。任何
-- 打开库的人——包括三个月后的自己——看到 31 就会得出错误结论，还可能以为要
-- 去补 29 个版本。所以删掉。
--
-- 顺带说明它为什么不可信：实测这张表 30 行、版本号 1..31，中间**缺 v22**，
-- 且全部 applied_at 落在 6 毫秒内（2026-09-28T03:16:14.658~.664）。也就是说
-- 它不是逐版本演进的记录，只是建库时一次 to_latest 批量写下的副产品。
--
-- 丢掉的 30 行是机器记账，不是用户数据；旧链那 31 段 SQL 完整保存在 git 历史
-- 里（6dbc582 删除 src/storage/migrations.rs 之前的版本）。
--
-- 为什么现在才能删：基线是冻结的 v1，改它对已有库完全无效——新引导读到
-- user_version >= 1 就跳过版本 1，而这张表正是建在基线里的。user_version 修好
-- 之后，新迁移才能在所有库上正常执行。这也正是「只追加、不改历史」的意义：
-- v1 照旧建这张表，v3 再删掉它，新库与老库终态一致。

DROP TABLE schema_migrations;
